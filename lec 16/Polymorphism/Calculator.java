class Calculator{
        //fresh method
        int add (int a , int b){
            return a+b;
        }
        
        //overloaded method
        int add(int a, int b, int c){
            return a+b+c;
        }

        //new overloaded method with different types
        double add(int a, int b, int c, double d){
            return a+b+c+d;
        }
        

}